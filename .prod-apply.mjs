import { chromium } from "@playwright/test";
const BASE = "https://cekharga-id.vercel.app";
const id = process.argv[2];
const b = await chromium.launch({ channel: "chrome" });
const ctx = await b.newContext();
const p = await ctx.newPage();
await p.goto(`${BASE}/admin/login`);
await p.getByLabel("Email").fill(process.env.QA_ADMIN_EMAIL);
await p.getByLabel("Kata sandi").fill(process.env.QA_ADMIN_PASSWORD);
await p.getByRole("button", { name: "Masuk" }).click();
await p.waitForURL(/\/admin$/, { timeout: 60000 });
await ctx.storageState({ path: "e2e/.auth/prod-admin.json" });
await p.goto(`${BASE}/admin/import/batch/${id}`);
const btn = p.getByRole("button", { name: /^Terapkan \d+ baris/ }).first();
await btn.waitFor({ timeout: 120000 });
console.log("klik:", await btn.innerText());
await btn.click();
await p.getByText(/\d+ berhasil · \d+ gagal · \d+ dilewati/).first().waitFor({ timeout: 300000 });
console.log((await p.getByText(/\d+ berhasil · \d+ gagal · \d+ dilewati/).first().innerText()));
await b.close();
